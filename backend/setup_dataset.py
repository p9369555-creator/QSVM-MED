# File: backend/setup_dataset.py
import os
import cv2
import numpy as np

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
DATASET_DIR = os.path.join(BASE_DIR, "brain_mri_dataset")

# Create required Kaggle-style class folders
NOTUMOR_DIR = os.path.join(DATASET_DIR, "notumor")
TUMOR_DIR = os.path.join(DATASET_DIR, "tumor")

os.makedirs(NOTUMOR_DIR, exist_ok=True)
os.makedirs(TUMOR_DIR, exist_ok=True)

print("==========================================================")
print(" QSVM-Med: Generating Structured Brain MRI Dataset Setup")
print("==========================================================")

rng = np.random.default_rng(2026)
yy, xx = np.mgrid[0:128, 0:128]

total_patients = 50  # 35 Normal patients, 15 Tumor patients with multiple slices each
scans_per_patient = 8

image_count = {"notumor": 0, "tumor": 0}

for p in range(1, total_patients + 1):
    is_tumor_patient = p > 35  # Patients 1-35 are healthy, 36-50 have tumors
    patient_id = f"patient_{p:03d}"
    class_folder = TUMOR_DIR if is_tumor_patient else NOTUMOR_DIR
    category_key = "tumor" if is_tumor_patient else "notumor"

    # Patient-specific anatomical baseline variance
    cx = rng.uniform(62.0, 66.0)
    cy = rng.uniform(62.0, 66.0)
    rx = rng.uniform(44.0, 48.0)
    ry = rng.uniform(50.0, 54.0)

    for s in range(scans_per_patient):
        img = np.zeros((128, 128), dtype=np.float32)
        ellipse_dist = ((xx - cx) / rx) ** 2 + ((yy - cy) / ry) ** 2

        brain_mask = ellipse_dist < 0.90
        skull_mask = (ellipse_dist <= 1.05) & (ellipse_dist >= 0.90)

        img[brain_mask] = rng.uniform(85.0, 105.0)
        img[skull_mask] = rng.uniform(150.0, 180.0)

        # Cortical texture
        noise = cv2.GaussianBlur(rng.normal(0.0, 10.0, size=(128, 128)), (5, 5), 1.2)
        img[brain_mask] += noise[brain_mask]

        # Ventricles
        v_left = (((xx - (cx - 7)) / 5.0) ** 2 + ((yy - cy) / 12.0) ** 2) < 1.0
        v_right = (((xx - (cx + 7)) / 5.0) ** 2 + ((yy - cy) / 12.0) ** 2) < 1.0
        img[v_left | v_right] = rng.uniform(25.0, 38.0)

        # If tumor patient, inject hyperintense intracranial lesion consistent across slices
        if is_tumor_patient:
            tx = cx + 16.0 * np.cos(p)
            ty = cy + 16.0 * np.sin(p)
            tumor_radius = 12.0 + (s * 0.3)
            dist_sq = (xx - tx) ** 2 + (yy - ty) ** 2
            core = np.exp(-dist_sq / (2.0 * (tumor_radius * 0.8) ** 2))
            img += core * 135.0 * brain_mask

        scan_noise = rng.normal(0.0, 3.0, size=(128, 128))
        final_img = np.clip(img + scan_noise, 0, 255).astype(np.uint8)

        filename = f"{patient_id}_slice_{s+1:02d}.png"
        cv2.imwrite(os.path.join(class_folder, filename), final_img)
        image_count[category_key] += 1

print(f"[SUCCESS] Created structured dataset inside: {DATASET_DIR}")
print(f"  - Normal Scans (`notumor/`): {image_count['notumor']} images")
print(f"  - Tumor Scans (`tumor/`): {image_count['tumor']} images")
print("Now you can run: python train_brain_mri.py")

with open(os.path.join(DATASET_DIR, "SYNTHETIC_DATA.txt"), "w") as _f:
    _f.write("These images were generated by setup_dataset.py (drawn ellipses + Gaussian blobs). NOT real MRI.\n")
print("[WARNING] This is SYNTHETIC demo data, not real MRI. For real results run: python train_brain_mri.py")
